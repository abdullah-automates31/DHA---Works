// Local-only Supabase settings. Everything here is FAKE and exists so phone sign-in can be tested offline:
// Auth accepts these fixed codes for these numbers and sends no WhatsApp/SMS. Keys are E.164 without "+"
// because Auth compares the number the app sends ("+92...").
export const LOCAL_TEST_OTPS = {
  923001234567: '123456',
  923211234567: '654321',
  923331234567: '112233',
  923451234567: '445566',
  923561234567: '778899',
};

const LOCAL_MARKER = '# ---- LOCAL ONLY (generated by scripts/local-supabase.mjs; never copy into supabase/config.toml) ----';

/** Returns text with the [name] table (header and body, up to the next table header) removed. */
export function removeTable(text, name) {
  const lines = text.split('\n');
  const out = [];
  let skipping = false;
  for (const line of lines) {
    const header = line.match(/^\s*\[([^\]]+)\]\s*(#.*)?\r?$/);
    if (header) skipping = header[1].trim() === name;
    if (!skipping) out.push(line);
  }
  return out.join('\n');
}

/** Shared config + the local-only OTP table and a fake-credential Twilio table (needed for Auth to accept test numbers). */
export function buildLocalConfig(sharedText) {
  const marker = sharedText.indexOf(LOCAL_MARKER);
  const shared = marker === -1 ? sharedText : sharedText.slice(0, marker);
  const base = removeTable(removeTable(shared, 'auth.sms.test_otp'), 'auth.sms.twilio').replace(/\s+$/, '\n');
  const otps = Object.entries(LOCAL_TEST_OTPS).map(([phone, code]) => `${phone} = "${code}"`).join('\n');
  return `${base}
${LOCAL_MARKER}
[auth.sms.test_otp]
${otps}

[auth.sms.twilio]
enabled = true
account_sid = "local-fake"
message_service_sid = "local-fake"
auth_token = "local-fake"
`;
}

const ALLOWED = {
  start: null,
  stop: null,
  status: null,
  test: ['db'],
  db: ['reset', 'lint'],
  functions: ['serve'],
};
const FORBIDDEN_FLAGS = ['--linked', '--db-url', '--project-ref', '--workdir'];

/** Local wrapper only runs commands that cannot reach a hosted project. Returns an error message or null. */
export function checkLocalArgs(args) {
  const [command, sub] = args;
  if (!command || !(command in ALLOWED)) {
    return `"${command ?? ''}" is not allowed here. Allowed: start, stop, status, test db, db reset, db lint, functions serve. Run other commands with the plain supabase CLI from the repo root.`;
  }
  const subs = ALLOWED[command];
  if (subs && !subs.includes(sub)) return `"${command} ${sub ?? ''}" is not allowed here. Allowed: ${subs.map((s) => `${command} ${s}`).join(', ')}.`;
  const flag = args.find((a) => FORBIDDEN_FLAGS.some((f) => a === f || a.startsWith(`${f}=`)));
  if (flag) return `${flag} is not allowed with the local wrapper.`;
  return null;
}
